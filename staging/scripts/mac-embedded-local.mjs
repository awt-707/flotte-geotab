const hash=bytes=>createHash('sha256').update(bytes).digest('hex');

export async function verifyEmbeddedMacKit(directory=root) {
  const base=await fs.realpath(directory),file=path.join(base,'manifest.json'),stat=await fs.lstat(file);
  if(!stat.isFile()||stat.isSymbolicLink()||stat.nlink!==1||stat.size>262144)throw Error('Manifest du kit invalide.');
  const manifest=JSON.parse(await fs.readFile(file,'utf8'));
  if(manifest.format!=='ludy-embedded-mac-source-v1'||!/^\d+\.\d+\.\d+$/.test(manifest.version||'')||!Array.isArray(manifest.files)||manifest.files.length<20||manifest.files.length>1024)throw Error('Format du kit invalide.');
  const expected=new Set();let totalBytes=0;
  for(const entry of manifest.files) {
    if(typeof entry.path!=='string'||entry.path.includes('\\')||path.posix.isAbsolute(entry.path)||entry.path.split('/').some(p=>!p||p==='.'||p==='..')||expected.has(entry.path)||!/^[a-f0-9]{64}$/.test(entry.sha256||''))throw Error('Entrée du manifest invalide.');
    expected.add(entry.path);
    const filename=path.join(base,entry.path),item=await fs.lstat(filename);
    if(!item.isFile()||item.isSymbolicLink()||item.nlink!==1||item.size>30*1024*1024||await fs.realpath(filename)!==filename)throw Error('Source du kit invalide : '+entry.path);
    const bytes=await fs.readFile(filename);totalBytes+=bytes.length;
    if(hash(bytes)!==entry.sha256)throw Error('Source incomplète ou modifiée : '+entry.path+'. Extrayez à nouveau le kit.');
  }
  for(const name of ['desktop-public.json','Preparer Ludy Mac.command','staging/scripts/mac-embedded-local.mjs','staging/scripts/build-embedded-desktop.mjs','staging/scripts/build-desktop.mjs','staging/scripts/paths.mjs','staging/scripts/mac-local-test.mjs','staging/desktop/package.json','staging/desktop/package-lock.json','staging/desktop/config.cjs','staging/desktop/embedded-config.cjs','staging/desktop/embedded-main.cjs','staging/desktop/embedded-bootstrap.cjs','staging/desktop-runtime/server.mjs','staging/package.json','staging/package-lock.json'])if(!expected.has(name))throw Error('Source requise absente : '+name);
  async function walk(relative='') {
    for(const entry of await fs.readdir(path.join(base,relative),{withFileTypes:true})) {
      const current=relative?relative+'/'+entry.name:entry.name;
      // These directories are generated by this runner and rebuilt from locks.
      if(['staging/.local','staging/desktop/node_modules'].includes(current)) {
        if(!entry.isDirectory()||entry.isSymbolicLink())throw Error('Dossier généré invalide.');
        continue;
      }
      if(entry.isSymbolicLink())throw Error('Lien symbolique inattendu : '+current);
      if(entry.isDirectory())await walk(current);
      else if(!entry.isFile()||!expected.has(current)&&current!=='manifest.json'&&entry.name!=='.DS_Store')throw Error('Fichier inattendu dans les sources : '+current);
    }
  }
  await walk();
  const config=readEmbeddedConfig(path.join(base,'desktop-public.json'));
  const desktop=JSON.parse(await fs.readFile(path.join(base,'staging/desktop/package.json'),'utf8'));
  if(manifest.projectRef!==config.projectRef||manifest.version!==desktop.version||manifest.totalBytes!==totalBytes)throw Error('Identité du kit incohérente.');
  return manifest;
}
function runProcess(name,args,options={}) {
  return new Promise((resolve,reject)=>{
    const child=spawn(name,args,{stdio:'inherit',...options});child.once('error',reject);
    child.once('exit',(code,signal)=>code===0?resolve():reject(Error(path.basename(name)+' interrompu ('+(signal||code)+'). Conservez le message du Terminal.')));
  });
}
export async function prepareEmbeddedMac({directory=root,host={platform:process.platform,arch:process.arch,nodeVersion:process.versions.node},verify=verifyEmbeddedMacKit,
  readMacVersion=async()=>(await command('/usr/bin/sw_vers',['-productVersion'])).stdout.trim(),
  checkTools=async()=>{for(const file of ['/usr/bin/codesign','/usr/bin/curl'])await fs.access(file,constants.X_OK);},
  run=runProcess,loadBuilder=async base=>import(pathToFileURL(path.join(base,'staging/scripts/build-embedded-desktop.mjs')).href),log=console.log}={}) {
  validateMacHost(host);validateMacHost({...host,macVersion:await readMacVersion()});
  const manifest=await verify(directory);await checkTools();
  log('Kit source '+manifest.version+' vérifié. Installation des outils de construction…');
  await run('npm',['ci','--include=dev','--ignore-scripts','--no-audit','--no-fund'],{cwd:path.join(directory,'staging/desktop'),env:{...process.env,ELECTRON_SKIP_BINARY_DOWNLOAD:'1'}});
  log('Construction native du client et du serveur Ludy. Aucun accès Supabase pendant cette préparation.');
  const {main}=await loadBuilder(directory),result=await main(['--config',path.join(directory,'desktop-public.json'),'--target','macos-'+host.arch,'--mac-local-test']);
  const release=path.join(await fs.realpath(directory),'staging/.local/releases/embedded-desktop');
  if(result?.target!=='macos-'+host.arch||result.version!==manifest.version||result.projectRef!==manifest.projectRef||result.signing!=='adhoc-local-test'||result.signed!==true||result.notarized!==false||result.distributable!==false||!path.isAbsolute(result.appPath||'')||!path.resolve(result.appPath).startsWith(release+path.sep)||path.basename(result.appPath)!=='Ludy.app')throw Error('Le résultat de construction ne correspond pas au test Mac local attendu.');
  await run('/usr/bin/codesign',['--verify','--deep','--strict','--verbose=2',result.appPath]);
  log('Signature ad hoc locale vérifiée. Application : '+result.appPath);
  log('Ouvrez Ludy.app pour tester la connexion au projet de production. La préparation n’a lancé ni collecte ni migration.');
  log('Cette application est réservée au test sur ce Mac ; elle n’est ni signée Developer ID ni notariée.');
  return result;
}
export async function main(args=process.argv.slice(2)) {
  if(args.length===1&&args[0]==='--verify'){const result=await verifyEmbeddedMacKit();console.log(JSON.stringify({ok:true,version:result.version,files:result.files.length,projectRef:result.projectRef,productionAccess:false},null,2));return result;}
  if(args.length)throw Error('Option inconnue. Utilisez --verify pour vérifier uniquement les sources.');
  return prepareEmbeddedMac();
}
if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href)main().catch(error=>{console.error('Préparation arrêtée : '+error.message);process.exitCode=1;});
