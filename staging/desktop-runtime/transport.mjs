import {randomBytes} from 'node:crypto';
import {isAdministrativeOperation,isManagerOperation} from './admin-context.mjs';
const failure=(message='La collecte appartient à un autre poste.',status=409)=>Object.assign(Error(message),{status});
export function createDesktopRpc({config,getSession,fetchFn=fetch}){
  return async(name,args,{signal}={})=>{
    const session=getSession();if(!session)throw failure('Connexion Ludy requise.',401);
    const response=await fetchFn(config.supabaseUrl+'/rest/v1/rpc/'+name,{method:'POST',redirect:'error',
      signal:signal?AbortSignal.any([signal,AbortSignal.timeout(15000)]):AbortSignal.timeout(15000),
      headers:{apikey:config.publishableKey,Authorization:'Bearer '+session.token,'Content-Type':'application/json'},body:JSON.stringify(args)});
    const body=await response.json().catch(()=>null);
    if(!response.ok)throw Object.assign(failure(response.status===401?'Session Ludy expirée.':'Coordination Supabase indisponible.',response.status),{code:body?.code});
    return body;
  };
}
/** A transport belongs to ONE session/lease generation. Its fence never changes. */
export function createDesktopTransport({config,deviceId,getSession,rpc,fence=null,signal,fetchFn=fetch}){
  const serviceKey='desktop-internal-'+randomBytes(32).toString('hex');
  const guard=()=>{if(signal?.aborted)throw failure();const session=getSession();if(!session)throw failure('Connexion Ludy requise.',401);return session;};
  async function request(input,options={}){
    const session=guard(),url=new URL(input),headers=new Headers(options.headers);
    const requestSignal=AbortSignal.any([...(signal?[signal]:[]),...(options.signal?[options.signal]:[])]);
    if(url.origin!==config.supabaseUrl){
      if(fence===null)throw failure();
      // These URLs are generated by existing provider clients, never by renderer input.
      return fetchFn(input,{...options,signal:requestSignal});
    }
    if(headers.get('authorization')!=='Bearer '+serviceKey){
      // User requests retain their own token and RLS; never attach an internal key.
      headers.set('apikey',config.publishableKey);
      return fetchFn(input,{...options,headers,redirect:'error',signal:requestSignal});
    }
    const method=(options.method||'GET').toUpperCase();
    if(!url.pathname.startsWith('/rest/v1/'))throw failure('Opération interne invalide.',400);
    const resource=decodeURIComponent(url.pathname.slice('/rest/v1/'.length));
    const manager=isManagerOperation(resource,method);
    if((session.role!=='admin'&&!manager)||url.pathname==='/rest/v1/profiles'){
      if(method!=='GET')throw failure('Accès administrateur requis.',403);
      headers.set('apikey',config.publishableKey);headers.set('authorization','Bearer '+session.token);
      return fetchFn(input,{...options,headers,redirect:'error',signal:requestSignal});
    }
    const manual=isAdministrativeOperation(resource,method);
    if(method!=='GET'&&fence===null&&!manual&&!manager)throw failure();
    const params={};for(const [key,v]of url.searchParams){if(Object.hasOwn(params,key))params[key]=[].concat(params[key],v);else params[key]=v;}
    const result=await rpc(manager?'desktop_manager_request':manual?'desktop_admin_request':'desktop_worker_request',{...(manager?{}:{p_device_id:deviceId}),...(manual||manager?{}:{p_fence:fence}),p_resource:resource,p_method:method,p_params:params,
      p_body:options.body===undefined?null:JSON.parse(options.body),p_prefer:headers.get('prefer')||null},{signal:requestSignal});
    guard();
    if(!result||!Number.isInteger(result.status)||result.status<200||result.status>599)throw failure('Réponse de coordination invalide.',502);
    return new Response(result.status===204?null:JSON.stringify(result.body),{status:result.status,headers:{'content-type':'application/json',...result.headers}});
  }
  return {serviceKey,fetchFn:request};
}
